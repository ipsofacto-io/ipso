// Package rules renders in-force decisions into the files AI coding agents read.
// One set of decisions becomes AGENTS.md, CLAUDE.md, GEMINI.md, Copilot instructions,
// Cursor rules, and Kiro steering files. The contract is ADR-0072.
package rules

import (
	"bytes"
	"encoding/json"
	"errors"
	"fmt"
	"io/fs"
	"os"
	"path"
	"regexp"
	"slices"
	"strings"
	"unicode"

	"github.com/ipsofacto-io/ipso/internal/edr"
)

const (
	beginMarker = "<!-- ipso:rules:begin. Generated by ipso rules generate. Edit the decision, then regenerate. -->"
	endMarker   = "<!-- ipso:rules:end -->"
	// ownedMarker is the line that lets a later run replace or remove a file it wrote.
	ownedMarker = "<!-- ipso:rules:generated. Generated by ipso rules generate. Edit the decision, then regenerate. -->"
	// markerPrefix is what decision text may not contain, so it cannot close a block early.
	markerPrefix = "<!-- ipso:rules:"
	// SensitiveTag on a record keeps its title and text out of every generated file.
	SensitiveTag = "sensitive"
	// maxStatement bounds one decision, because agents load these files on every turn.
	maxStatement = 2000

	preamble = "These engineering decisions are in force in this repository. They bind every edit. To change one, propose a new decision. Do not edit the record."

	copilotFile = ".github/copilot-instructions.md"
	cursorDir   = ".cursor/rules"
	kiroDir     = ".kiro/steering"
	copilotDir  = ".github/instructions"
	ownedPrefix = "ipso-"
)

// memoryFiles are the files an agent reads from the directory it works in and its parents.
var memoryFiles = []string{"AGENTS.md", "CLAUDE.md", "GEMINI.md"}

// skippedDirs are not searched for stale blocks, because their files are not this repository's.
var skippedDirs = map[string]bool{".git": true, ".ipso": true, "node_modules": true, "vendor": true}

// globChars is what a path glob may hold. Every format below can carry these characters
// unquoted, and none of them can end a list or a YAML scalar.
var globChars = regexp.MustCompile(`^[A-Za-z0-9._/*?@+~=-]+$`)

// slugChars is the EDR slug grammar, repeated because a slug names a file here.
var slugChars = regexp.MustCompile(`^[a-z0-9]+(-[a-z0-9]+)*$`)

// Decision is what a generated file says about one in-force record.
type Decision struct {
	Slug        string
	Title       string
	Status      string
	Criticality string
	// Record is the slash-separated path of the EDR file.
	Record string
	// Statement is the body of the Decision section. Nothing else from the record is read.
	Statement string
	// Paths are the globs of the scope. Empty means the whole repository.
	Paths     []string
	Env       []string
	Sensitive bool
}

// Change is one file to write or remove, by slash-separated path from the repository root.
type Change struct {
	Path   string
	Remove bool
	Data   []byte
}

// Plan compares the files these decisions need with the repository and returns the changes,
// sorted by path. It writes nothing. A malformed block, a file at a generated path that this
// command did not write, or a symlink on the way to a generated path is an error. decisionGlobs
// are the config globs. A generated file must not match one, or it would be read as a decision.
func Plan(repo *os.Root, decisions []Decision, decisionGlobs []string) ([]Change, error) {
	ordered, err := sorted(decisions)
	if err != nil {
		return nil, err
	}
	blocks, err := memoryBlocks(repo, ordered, decisionGlobs)
	if err != nil {
		return nil, err
	}
	owned, err := ownedFiles(ordered)
	if err != nil {
		return nil, err
	}

	existing, err := existingGenerated(repo)
	if err != nil {
		return nil, err
	}
	var changes []Change
	for _, name := range existing.blocks {
		if _, ok := blocks[name]; !ok {
			blocks[name] = ""
		}
	}
	for name, block := range blocks {
		change, err := planBlock(repo, name, block)
		if err != nil {
			return nil, err
		}
		if change != nil {
			changes = append(changes, *change)
		}
	}
	for name, data := range owned {
		change, err := planOwned(repo, name, data)
		if err != nil {
			return nil, err
		}
		if change != nil {
			changes = append(changes, *change)
		}
	}
	for _, name := range existing.owned {
		if _, ok := owned[name]; !ok {
			changes = append(changes, Change{Path: name, Remove: true})
		}
	}
	slices.SortFunc(changes, func(a, b Change) int { return strings.Compare(a.Path, b.Path) })
	for _, change := range changes {
		if !change.Remove && matchesAny(decisionGlobs, change.Path) {
			return nil, fmt.Errorf("%s: matches the decisions glob in the config", change.Path)
		}
	}
	return changes, nil
}

// Apply writes the changes from Plan. Each write goes through a temporary file and a rename,
// so an interrupted run cannot truncate a file that also holds hand-written text.
func Apply(repo *os.Root, changes []Change) error {
	for _, change := range changes {
		if err := RefuseSymlinks(repo, change.Path); err != nil {
			return err
		}
		if change.Remove {
			if err := repo.Remove(change.Path); err != nil {
				return err
			}
			if isOwnedPath(change.Path) {
				removeEmptyParents(repo, change.Path)
			}
			continue
		}
		if dir := path.Dir(change.Path); dir != "." {
			if err := repo.MkdirAll(dir, 0o755); err != nil {
				return err
			}
		}
		mode := fs.FileMode(0o644)
		if info, err := repo.Lstat(change.Path); err == nil {
			mode = info.Mode().Perm()
		}
		if err := replaceFile(repo, change.Path, change.Data, mode); err != nil {
			return err
		}
	}
	return nil
}

// removeEmptyParents takes away directories an owned file was the last entry of. Remove refuses
// a directory that still holds something.
func removeEmptyParents(repo *os.Root, name string) {
	for dir := path.Dir(name); dir != "."; dir = path.Dir(dir) {
		if err := repo.Remove(dir); err != nil {
			return
		}
	}
}

// replaceFile creates the temporary file with O_EXCL, so a planted link at that name is refused.
func replaceFile(repo *os.Root, name string, data []byte, mode fs.FileMode) error {
	temp := name + ".ipso-tmp"
	if err := repo.Remove(temp); err != nil && !errors.Is(err, fs.ErrNotExist) {
		return err
	}
	file, err := repo.OpenFile(temp, os.O_WRONLY|os.O_CREATE|os.O_EXCL, mode)
	if err != nil {
		return err
	}
	_, err = file.Write(data)
	if closeErr := file.Close(); err == nil {
		err = closeErr
	}
	if err == nil {
		err = repo.Rename(temp, name)
	}
	if err != nil {
		_ = repo.Remove(temp)
	}
	return err
}

func sorted(decisions []Decision) ([]Decision, error) {
	ordered := slices.Clone(decisions)
	slices.SortFunc(ordered, func(a, b Decision) int { return strings.Compare(a.Slug, b.Slug) })
	for i, item := range ordered {
		if !slugChars.MatchString(item.Slug) {
			return nil, fmt.Errorf("%s: slug %q cannot name a file", item.Record, item.Slug)
		}
		if i > 0 && ordered[i-1].Slug == item.Slug {
			return nil, fmt.Errorf("%s and %s share slug %s", ordered[i-1].Record, item.Record, item.Slug)
		}
		for _, glob := range item.Paths {
			if err := CheckGlob(glob); err != nil {
				return nil, fmt.Errorf("%s: %w", item.Record, err)
			}
		}
	}
	return ordered, nil
}

// CheckGlob reports whether every generated format can carry a path glob.
func CheckGlob(glob string) error {
	if !globChars.MatchString(glob) {
		return fmt.Errorf("path %q has a character the generated files cannot carry", glob)
	}
	if strings.HasPrefix(glob, "/") || slices.Contains(strings.Split(glob, "/"), "..") {
		return fmt.Errorf("path %q leaves the repository", glob)
	}
	return nil
}

// section is one decision in a block, with the globs that placed it in that file.
type section struct {
	decision Decision
	globs    []string
}

// memoryBlocks returns the block text for each memory file. A decision for the whole repository
// goes to the root. A path glob goes to the deepest directory that exists on its literal prefix,
// because these formats scope by where the file sits.
func memoryBlocks(repo *os.Root, decisions []Decision, decisionGlobs []string) (map[string]string, error) {
	byDir := map[string][]section{}
	var wide []section
	for _, item := range decisions {
		if len(item.Paths) == 0 {
			wide = append(wide, section{decision: item})
			continue
		}
		perDir := map[string][]string{}
		for _, glob := range item.Paths {
			dir, err := literalDir(repo, glob, decisionGlobs)
			if err != nil {
				return nil, err
			}
			perDir[dir] = append(perDir[dir], glob)
		}
		for dir, globs := range perDir {
			byDir[dir] = append(byDir[dir], section{decision: item, globs: globs})
		}
	}
	byDir["."] = slices.Concat(wide, byDir["."])

	blocks := map[string]string{}
	for dir, sections := range byDir {
		if len(sections) == 0 {
			continue
		}
		slices.SortFunc(sections, func(a, b section) int { return strings.Compare(a.decision.Slug, b.decision.Slug) })
		block := renderBlock(sections)
		for _, name := range memoryFiles {
			blocks[path.Join(dir, name)] = block
		}
	}
	if len(wide) > 0 {
		blocks[copilotFile] = renderBlock(wide)
	}
	return blocks, nil
}

// literalDir walks a glob's literal segments while they name real directories, and stops before
// a directory where a memory file would be read as a decision.
func literalDir(repo *os.Root, glob string, decisionGlobs []string) (string, error) {
	dir := "."
	for _, segment := range strings.Split(glob, "/") {
		if strings.ContainsAny(segment, "*?") {
			break
		}
		next := path.Join(dir, segment)
		if skippedDirs[segment] || holdsDecisions(next, decisionGlobs) {
			break
		}
		info, err := repo.Lstat(next)
		if errors.Is(err, fs.ErrNotExist) {
			break
		}
		if err != nil {
			return "", err
		}
		if !info.IsDir() {
			break
		}
		dir = next
	}
	return dir, nil
}

func holdsDecisions(dir string, decisionGlobs []string) bool {
	for _, name := range memoryFiles {
		if matchesAny(decisionGlobs, path.Join(dir, name)) {
			return true
		}
	}
	return false
}

func matchesAny(globs []string, name string) bool {
	for _, glob := range globs {
		if edr.MatchPath(glob, name) {
			return true
		}
	}
	return false
}

func renderBlock(sections []section) string {
	var out strings.Builder
	out.WriteString(beginMarker + "\n\n## Engineering decisions in force\n\n" + preamble + "\n")
	for _, item := range sections {
		out.WriteString("\n" + renderDecision(item.decision, item.globs, "###"))
	}
	out.WriteString("\n" + endMarker)
	return out.String()
}

func renderDecision(item Decision, globs []string, heading string) string {
	var out strings.Builder
	if item.Sensitive {
		fmt.Fprintf(&out, "%s Decision `%s`\n\n", heading, item.Slug)
	} else {
		fmt.Fprintf(&out, "%s %s (`%s`)\n\n", heading, oneLine(item.Title), item.Slug)
	}
	fields := []string{"Criticality: " + oneLine(item.Criticality), "State: " + BrandState(item.Status)}
	if len(globs) > 0 {
		quoted := make([]string, len(globs))
		for i, glob := range globs {
			quoted[i] = "`" + glob + "`"
		}
		fields = append(fields, "Applies to: "+strings.Join(quoted, ", "))
	}
	if len(item.Env) > 0 {
		fields = append(fields, "Environments: "+oneLine(strings.Join(item.Env, ", ")))
	}
	fields = append(fields, "Record: `"+oneLine(item.Record)+"`")
	out.WriteString(strings.Join(fields, ". ") + ".\n\n")
	if item.Sensitive {
		out.WriteString("This decision is marked sensitive. Read the record.\n")
		return out.String()
	}
	out.WriteString(Statement(item.Statement) + "\n")
	return out.String()
}

// Statement returns the decision text, bounded, with no line that could close a block.
func Statement(raw string) string {
	text := strings.ReplaceAll(strings.TrimSpace(raw), markerPrefix, "&lt;!-- ipso:rules:")
	runes := []rune(text)
	if len(runes) > maxStatement {
		return string(runes[:maxStatement]) + "\n\nThis text is cut. Read the record for the rest."
	}
	return text
}

// BrandState is the word section 2.2 shows for an internal state.
func BrandState(status string) string {
	switch status {
	case "verified":
		return "Verified"
	case "needs-review":
		return "Needs review"
	default:
		return "Under verification"
	}
}

func oneLine(text string) string {
	cleaned := strings.Map(func(r rune) rune {
		if unicode.IsControl(r) {
			return ' '
		}
		return r
	}, text)
	return strings.ReplaceAll(cleaned, markerPrefix, "&lt;!-- ipso:rules:")
}

// ownedFiles returns the files that hold one decision each and that this command owns whole.
// These formats scope in their front matter.
func ownedFiles(decisions []Decision) (map[string][]byte, error) {
	files := map[string][]byte{}
	for _, item := range decisions {
		description := item.Slug
		if !item.Sensitive {
			description = oneLine(item.Title)
		}
		quoted, err := yamlString(description)
		if err != nil {
			return nil, err
		}
		body := ownedMarker + "\n\n" + preamble + "\n\n" + renderDecision(item, item.Paths, "#")

		cursor := "---\ndescription: " + quoted + "\n"
		kiro := "---\n"
		if len(item.Paths) == 0 {
			cursor += "alwaysApply: true\n"
			kiro += "inclusion: always\n"
		} else {
			cursor += "globs: " + strings.Join(item.Paths, ", ") + "\nalwaysApply: false\n"
			patterns, err := yamlStrings(item.Paths)
			if err != nil {
				return nil, err
			}
			kiro += "inclusion: fileMatch\nfileMatchPattern: " + patterns + "\n"
			files[copilotDir+"/"+ownedPrefix+item.Slug+".instructions.md"] = []byte("---\napplyTo: \"" + strings.Join(item.Paths, ",") + "\"\ndescription: " + quoted + "\n---\n\n" + body)
		}
		files[cursorDir+"/"+ownedPrefix+item.Slug+".mdc"] = []byte(cursor + "---\n\n" + body)
		files[kiroDir+"/"+ownedPrefix+item.Slug+".md"] = []byte(kiro + "---\n\n" + body)
	}
	return files, nil
}

// yamlString quotes one value. A JSON string is a YAML double-quoted scalar.
func yamlString(value string) (string, error) {
	var out bytes.Buffer
	encoder := json.NewEncoder(&out)
	encoder.SetEscapeHTML(false)
	if err := encoder.Encode(value); err != nil {
		return "", err
	}
	return strings.TrimSpace(out.String()), nil
}

func yamlStrings(values []string) (string, error) {
	quoted := make([]string, len(values))
	for i, value := range values {
		text, err := yamlString(value)
		if err != nil {
			return "", err
		}
		quoted[i] = text
	}
	return "[" + strings.Join(quoted, ", ") + "]", nil
}

type generated struct {
	blocks []string
	owned  []string
}

// existingGenerated finds what earlier runs left: memory files with a block, and owned files
// that carry the marker. A file without the marker is the user's and is never listed.
func existingGenerated(repo *os.Root) (generated, error) {
	var found generated
	err := fs.WalkDir(repo.FS(), ".", func(name string, entry fs.DirEntry, walkErr error) error {
		if walkErr != nil {
			return walkErr
		}
		if entry.IsDir() {
			if skippedDirs[entry.Name()] {
				return fs.SkipDir
			}
			return nil
		}
		if !entry.Type().IsRegular() {
			return nil
		}
		isMemory := slices.Contains(memoryFiles, entry.Name()) || name == copilotFile
		isOwned := isOwnedPath(name)
		if !isMemory && !isOwned {
			return nil
		}
		data, err := repo.ReadFile(name)
		if err != nil {
			return err
		}
		switch {
		case isMemory && hasLine(data, beginMarker):
			found.blocks = append(found.blocks, name)
		case isOwned && hasLine(data, ownedMarker):
			found.owned = append(found.owned, name)
		}
		return nil
	})
	return found, err
}

func isOwnedPath(name string) bool {
	dir, base := path.Split(name)
	if !strings.HasPrefix(base, ownedPrefix) {
		return false
	}
	switch strings.TrimSuffix(dir, "/") {
	case cursorDir:
		return strings.HasSuffix(base, ".mdc")
	case kiroDir:
		return strings.HasSuffix(base, ".md")
	case copilotDir:
		return strings.HasSuffix(base, ".instructions.md")
	}
	return false
}

func hasLine(data []byte, line string) bool {
	return slices.Contains(strings.Split(strings.ReplaceAll(string(data), "\r\n", "\n"), "\n"), line)
}

// planBlock returns the change that puts block into the file, or takes it out when block is empty.
func planBlock(repo *os.Root, name, block string) (*Change, error) {
	if err := RefuseSymlinks(repo, name); err != nil {
		return nil, err
	}
	current, err := repo.ReadFile(name)
	if err != nil && !errors.Is(err, fs.ErrNotExist) {
		return nil, err
	}
	text := string(current)
	before, after, had, err := splitBlock(text)
	if err != nil {
		return nil, fmt.Errorf("%s: %w", name, err)
	}
	if block == "" {
		kept := joinBlock(before, "", after)
		if strings.TrimSpace(kept) == "" {
			return &Change{Path: name, Remove: true}, nil
		}
		return &Change{Path: name, Data: []byte(kept)}, nil
	}
	if !had {
		before, after = text, ""
	}
	wanted := joinBlock(before, block, after)
	if wanted == text {
		return nil, nil
	}
	return &Change{Path: name, Data: []byte(wanted)}, nil
}

// splitBlock returns the text around the one block in a file. A second block, or a marker
// without its pair, is an error, because guessing could delete hand-written text.
func splitBlock(text string) (string, string, bool, error) {
	lines := strings.Split(text, "\n")
	begin, end := -1, -1
	for i, line := range lines {
		switch strings.TrimSuffix(line, "\r") {
		case beginMarker:
			if begin >= 0 {
				return "", "", false, errors.New("more than one ipso block")
			}
			begin = i
		case endMarker:
			if end >= 0 {
				return "", "", false, errors.New("more than one ipso block")
			}
			end = i
		}
	}
	if begin < 0 && end < 0 {
		return "", "", false, nil
	}
	if begin < 0 || end < begin {
		return "", "", false, errors.New("the ipso block markers do not pair")
	}
	return strings.Join(lines[:begin], "\n"), strings.Join(lines[end+1:], "\n"), true, nil
}

func joinBlock(before, block, after string) string {
	before = strings.TrimRight(before, " \t\r\n")
	after = strings.TrimLeft(after, " \t\r\n")
	parts := make([]string, 0, 3)
	for _, part := range []string{before, block, after} {
		if part != "" {
			parts = append(parts, strings.TrimRight(part, "\n"))
		}
	}
	if len(parts) == 0 {
		return ""
	}
	return strings.Join(parts, "\n\n") + "\n"
}

func planOwned(repo *os.Root, name string, data []byte) (*Change, error) {
	if err := RefuseSymlinks(repo, name); err != nil {
		return nil, err
	}
	current, err := repo.ReadFile(name)
	if errors.Is(err, fs.ErrNotExist) {
		return &Change{Path: name, Data: data}, nil
	}
	if err != nil {
		return nil, err
	}
	if !hasLine(current, ownedMarker) {
		return nil, fmt.Errorf("%s: exists and was not written by ipso rules generate", name)
	}
	if bytes.Equal(current, data) {
		return nil, nil
	}
	return &Change{Path: name, Data: data}, nil
}

// RefuseSymlinks stops a write from following a link to another file in the repository.
func RefuseSymlinks(repo *os.Root, name string) error {
	current := ""
	for _, segment := range strings.Split(name, "/") {
		current = path.Join(current, segment)
		info, err := repo.Lstat(current)
		if errors.Is(err, fs.ErrNotExist) {
			return nil
		}
		if err != nil {
			return err
		}
		if info.Mode()&fs.ModeSymlink != 0 {
			return fmt.Errorf("%s: %s is a symlink", name, current)
		}
	}
	return nil
}
